// ---------------------------------------------------------------------------
// AArch64 exception vector table — 16 entries × 128 bytes = 2048 bytes
// VBAR_EL1 must be aligned to 2048 bytes.
// ---------------------------------------------------------------------------

#[cfg(target_os = "none")]
core::arch::global_asm!(
    ".section .text.vectors, \"ax\"",
    ".balign 2048",
    ".global exception_vectors",
    "exception_vectors:",
    // EL1t (SP_EL0)
    ".balign 128",
    "    b   el1t_sync",
    ".balign 128",
    "    b   el1t_irq",
    ".balign 128",
    "    b   el1t_fiq",
    ".balign 128",
    "    b   el1t_serror",
    // EL1h (SP_EL1) — used by vivanta_kernel
    ".balign 128",
    "    b   el1h_sync",
    ".balign 128",
    "    b   el1h_irq",
    ".balign 128",
    "    b   el1h_fiq",
    ".balign 128",
    "    b   el1h_serror",
    // Lower EL AArch64
    ".balign 128",
    "    b   lower_aarch64_sync",
    ".balign 128",
    "    b   lower_aarch64_irq",
    ".balign 128",
    "    b   lower_aarch64_fiq",
    ".balign 128",
    "    b   lower_aarch64_serror",
    // Lower EL AArch32
    ".balign 128",
    "    b   lower_aarch32_sync",
    ".balign 128",
    "    b   lower_aarch32_irq",
    ".balign 128",
    "    b   lower_aarch32_fiq",
    ".balign 128",
    "    b   lower_aarch32_serror",
    // macro: save_and_halt — for synchronous exceptions / faults
    ".macro save_and_halt kind",
    "    sub   sp, sp, #(34 * 8)",
    "    stp   x0, x1,  [sp, #(0 * 8)]",
    "    stp   x2, x3,  [sp, #(2 * 8)]",
    "    stp   x4, x5,  [sp, #(4 * 8)]",
    "    stp   x6, x7,  [sp, #(6 * 8)]",
    "    stp   x8, x9,  [sp, #(8 * 8)]",
    "    stp   x10,x11, [sp, #(10 * 8)]",
    "    stp   x12,x13, [sp, #(12 * 8)]",
    "    stp   x14,x15, [sp, #(14 * 8)]",
    "    stp   x16,x17, [sp, #(16 * 8)]",
    "    stp   x18,x19, [sp, #(18 * 8)]",
    "    stp   x20,x21, [sp, #(20 * 8)]",
    "    stp   x22,x23, [sp, #(22 * 8)]",
    "    stp   x24,x25, [sp, #(24 * 8)]",
    "    stp   x26,x27, [sp, #(26 * 8)]",
    "    stp   x28,x29, [sp, #(28 * 8)]",
    "    str   x30,     [sp, #(30 * 8)]",
    "    add   x0, sp, #(34 * 8)",
    "    str   x0,      [sp, #(31 * 8)]",
    "    mrs   x1, elr_el1",
    "    str   x1,      [sp, #(32 * 8)]",
    "    mrs   x2, spsr_el1",
    "    str   x2,      [sp, #(33 * 8)]",
    "    mov   x0, sp",
    "    mov   x1, \\kind",
    "    mrs   x2, esr_el1",
    "    mrs   x3, far_el1",
    "    bl    exception_handler",
    "    b     .",
    ".endm",
    // macro: save_and_eret — for IRQs
    ".macro save_and_eret kind",
    "    sub   sp, sp, #(34 * 8)",
    "    stp   x0, x1,  [sp, #(0 * 8)]",
    "    stp   x2, x3,  [sp, #(2 * 8)]",
    "    stp   x4, x5,  [sp, #(4 * 8)]",
    "    stp   x6, x7,  [sp, #(6 * 8)]",
    "    stp   x8, x9,  [sp, #(8 * 8)]",
    "    stp   x10,x11, [sp, #(10 * 8)]",
    "    stp   x12,x13, [sp, #(12 * 8)]",
    "    stp   x14,x15, [sp, #(14 * 8)]",
    "    stp   x16,x17, [sp, #(16 * 8)]",
    "    stp   x18,x19, [sp, #(18 * 8)]",
    "    stp   x20,x21, [sp, #(20 * 8)]",
    "    stp   x22,x23, [sp, #(22 * 8)]",
    "    stp   x24,x25, [sp, #(24 * 8)]",
    "    stp   x26,x27, [sp, #(26 * 8)]",
    "    stp   x28,x29, [sp, #(28 * 8)]",
    "    str   x30,     [sp, #(30 * 8)]",
    "    add   x0, sp, #(34 * 8)",
    "    str   x0,      [sp, #(31 * 8)]",
    "    mrs   x1, elr_el1",
    "    str   x1,      [sp, #(32 * 8)]",
    "    mrs   x2, spsr_el1",
    "    str   x2,      [sp, #(33 * 8)]",
    "    mov   x0, sp",
    "    mov   x1, \\kind",
    "    mrs   x2, esr_el1",
    "    mrs   x3, far_el1",
    "    bl    irq_entry_handler",
    "    ldr   x30,     [sp, #(32 * 8)]",
    "    msr   elr_el1, x30",
    "    ldr   x30,     [sp, #(33 * 8)]",
    "    msr   spsr_el1, x30",
    "    ldr   x30,     [sp, #(31 * 8)]",
    "    sub   x30, x30, #(34 * 8)",
    "    mov   sp, x30",
    "    ldr   x30,     [sp, #(30 * 8)]",
    "    ldp   x28,x29, [sp, #(28 * 8)]",
    "    ldp   x26,x27, [sp, #(26 * 8)]",
    "    ldp   x24,x25, [sp, #(24 * 8)]",
    "    ldp   x22,x23, [sp, #(22 * 8)]",
    "    ldp   x20,x21, [sp, #(20 * 8)]",
    "    ldp   x18,x19, [sp, #(18 * 8)]",
    "    ldp   x16,x17, [sp, #(16 * 8)]",
    "    ldp   x14,x15, [sp, #(14 * 8)]",
    "    ldp   x12,x13, [sp, #(12 * 8)]",
    "    ldp   x10,x11, [sp, #(10 * 8)]",
    "    ldp   x8, x9,  [sp, #(8 * 8)]",
    "    ldp   x6, x7,  [sp, #(6 * 8)]",
    "    ldp   x4, x5,  [sp, #(4 * 8)]",
    "    ldp   x2, x3,  [sp, #(2 * 8)]",
    "    ldp   x0, x1,  [sp, #(0 * 8)]",
    "    add   sp, sp, #(34 * 8)",
    "    eret",
    ".endm",
    // macro: save_and_eret_sync — for SVC / sync exceptions from EL0
    ".macro save_and_eret_sync kind",
    "    sub   sp, sp, #(34 * 8)",
    "    stp   x0, x1,  [sp, #(0 * 8)]",
    "    stp   x2, x3,  [sp, #(2 * 8)]",
    "    stp   x4, x5,  [sp, #(4 * 8)]",
    "    stp   x6, x7,  [sp, #(6 * 8)]",
    "    stp   x8, x9,  [sp, #(8 * 8)]",
    "    stp   x10,x11, [sp, #(10 * 8)]",
    "    stp   x12,x13, [sp, #(12 * 8)]",
    "    stp   x14,x15, [sp, #(14 * 8)]",
    "    stp   x16,x17, [sp, #(16 * 8)]",
    "    stp   x18,x19, [sp, #(18 * 8)]",
    "    stp   x20,x21, [sp, #(20 * 8)]",
    "    stp   x22,x23, [sp, #(22 * 8)]",
    "    stp   x24,x25, [sp, #(24 * 8)]",
    "    stp   x26,x27, [sp, #(26 * 8)]",
    "    stp   x28,x29, [sp, #(28 * 8)]",
    "    str   x30,     [sp, #(30 * 8)]",
    "    add   x0, sp, #(34 * 8)",
    "    str   x0,      [sp, #(31 * 8)]",
    "    mrs   x1, elr_el1",
    "    str   x1,      [sp, #(32 * 8)]",
    "    mrs   x2, spsr_el1",
    "    str   x2,      [sp, #(33 * 8)]",
    "    mov   x0, sp",
    "    mov   x1, \\kind",
    "    mrs   x2, esr_el1",
    "    mrs   x3, far_el1",
    "    bl    el0_sync_handler",
    "    ldr   x30,     [sp, #(32 * 8)]",
    "    msr   elr_el1, x30",
    "    ldr   x30,     [sp, #(33 * 8)]",
    "    msr   spsr_el1, x30",
    "    ldr   x30,     [sp, #(31 * 8)]",
    "    sub   x30, x30, #(34 * 8)",
    "    mov   sp, x30",
    "    ldr   x30,     [sp, #(30 * 8)]",
    "    ldp   x28,x29, [sp, #(28 * 8)]",
    "    ldp   x26,x27, [sp, #(26 * 8)]",
    "    ldp   x24,x25, [sp, #(24 * 8)]",
    "    ldp   x22,x23, [sp, #(22 * 8)]",
    "    ldp   x20,x21, [sp, #(20 * 8)]",
    "    ldp   x18,x19, [sp, #(18 * 8)]",
    "    ldp   x16,x17, [sp, #(16 * 8)]",
    "    ldp   x14,x15, [sp, #(14 * 8)]",
    "    ldp   x12,x13, [sp, #(12 * 8)]",
    "    ldp   x10,x11, [sp, #(10 * 8)]",
    "    ldp   x8, x9,  [sp, #(8 * 8)]",
    "    ldp   x6, x7,  [sp, #(6 * 8)]",
    "    ldp   x4, x5,  [sp, #(4 * 8)]",
    "    ldp   x2, x3,  [sp, #(2 * 8)]",
    "    ldp   x0, x1,  [sp, #(0 * 8)]",
    "    add   sp, sp, #(34 * 8)",
    "    eret",
    ".endm",
    // Sync / fault vectors → halt
    "el1t_sync:         save_and_halt 0",
    "el1t_fiq:          save_and_halt 2",
    "el1t_serror:       save_and_halt 3",
    "el1h_sync:         save_and_halt 4",
    "el1h_fiq:          save_and_halt 6",
    "el1h_serror:       save_and_halt 7",
    "lower_aarch64_sync:  save_and_eret_sync 8",
    "lower_aarch64_fiq:   save_and_halt 10",
    "lower_aarch64_serror: save_and_halt 11",
    "lower_aarch32_sync:  save_and_halt 12",
    "lower_aarch32_fiq:   save_and_halt 14",
    "lower_aarch32_serror: save_and_halt 15",
    // IRQ vectors → handle and return
    "el1t_irq:          save_and_eret 1",
    "el1h_irq:          save_and_eret 5",
    "lower_aarch64_irq:   save_and_eret 9",
    "lower_aarch32_irq:   save_and_eret 13",
);
